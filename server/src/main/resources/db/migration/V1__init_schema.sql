-- 서울메이트 ERD v2.4 (Supabase Postgres, 17개 테이블)
-- 로그인 정보는 Supabase Auth(auth.users)가 관리한다. users.id = auth.users.id (토큰의 sub)
-- enum 은 VARCHAR 로 저장하고 값 검사는 서버 코드에서 한다
-- 모든 테이블에 RLS 를 켜고 허용 정책은 만들지 않는다 → 앱의 공개(anon) 키로는 테이블을 읽을 수 없고,
-- 테이블 소유자 권한으로 접속하는 Spring 만 읽고 쓴다 (API 명세 v1.4 0-0)

CREATE TABLE users (
    id                UUID         PRIMARY KEY,
    country           VARCHAR(2)   NOT NULL,
    role              VARCHAR(20)  NOT NULL,
    language          VARCHAR(2)   NOT NULL,
    nickname          VARCHAR(12)  UNIQUE,
    gender            VARCHAR(10),
    birth_year        INT,
    profile_image_url VARCHAR(500),
    bio               VARCHAR(200),
    verify_status     VARCHAR(20)  NOT NULL DEFAULT 'NONE',
    match_slots       INT          NOT NULL DEFAULT 1,
    status            VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    terms_agreed_at   TIMESTAMP    NOT NULL,
    created_at        TIMESTAMP    NOT NULL
);

CREATE TABLE match_preferences (
    user_id     UUID        PRIMARY KEY REFERENCES users (id),
    gender_pref VARCHAR(10) NOT NULL,
    age_groups  VARCHAR(20) NOT NULL
);

CREATE TABLE tags (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id BIGINT REFERENCES tags (id),
    category  VARCHAR(50),
    name_ko   VARCHAR(50) NOT NULL,
    name_ja   VARCHAR(50) NOT NULL,
    depth     INT         NOT NULL
);

CREATE TABLE user_tags (
    user_id UUID   NOT NULL REFERENCES users (id),
    tag_id  BIGINT NOT NULL REFERENCES tags (id),
    PRIMARY KEY (user_id, tag_id)
);

CREATE TABLE trips (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    traveler_id UUID      NOT NULL REFERENCES users (id),
    start_date  DATE      NOT NULL,
    end_date    DATE      NOT NULL,
    created_at  TIMESTAMP NOT NULL
);

CREATE TABLE secret_maps (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mate_id            UUID        NOT NULL REFERENCES users (id),
    title              VARCHAR(30) NOT NULL,
    caption            TEXT,
    caption_translated TEXT,
    created_at         TIMESTAMP   NOT NULL,
    updated_at         TIMESTAMP   NOT NULL
);

CREATE TABLE spots (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    map_id            BIGINT         NOT NULL REFERENCES secret_maps (id),
    name              VARCHAR(100)   NOT NULL,
    address           VARCHAR(255),
    lat               DECIMAL(10, 7) NOT NULL,
    lng               DECIMAL(10, 7) NOT NULL,
    tag_id            BIGINT REFERENCES tags (id),
    reason            TEXT,
    reason_translated TEXT,
    review            TEXT,
    review_translated TEXT,
    is_preview        BOOLEAN        NOT NULL DEFAULT FALSE,
    sort_order        INT            NOT NULL DEFAULT 0
);

CREATE TABLE spot_photos (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    spot_id    BIGINT       NOT NULL REFERENCES spots (id),
    url        VARCHAR(500) NOT NULL,
    sort_order INT          NOT NULL DEFAULT 0
);

CREATE TABLE matches (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trip_id            BIGINT      NOT NULL REFERENCES trips (id),
    traveler_id        UUID        NOT NULL REFERENCES users (id),
    mate_id            UUID        NOT NULL REFERENCES users (id),
    course_map_id      BIGINT REFERENCES secret_maps (id),
    required_visits    INT,
    status             VARCHAR(20) NOT NULL,
    chat_status        VARCHAR(20) NOT NULL DEFAULT 'LOCKED',
    traveler_chat_ok   BOOLEAN,
    mate_chat_ok       BOOLEAN,
    matched_at         TIMESTAMP   NOT NULL,
    course_selected_at TIMESTAMP,
    ended_at           TIMESTAMP
);
CREATE INDEX idx_match_mate_status ON matches (mate_id, status);
CREATE INDEX idx_match_traveler_status ON matches (traveler_id, status);
CREATE INDEX idx_match_course_map ON matches (course_map_id);

CREATE TABLE spot_visits (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id          BIGINT       NOT NULL REFERENCES matches (id),
    spot_id           BIGINT       NOT NULL REFERENCES spots (id),
    photo_url         VARCHAR(500) NOT NULL,
    review            TEXT,
    review_translated TEXT,
    verified_at       TIMESTAMP    NOT NULL,
    CONSTRAINT uk_visit_match_spot UNIQUE (match_id, spot_id)
);

CREATE TABLE visit_reactions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    visit_id           BIGINT    NOT NULL REFERENCES spot_visits (id),
    author_id          UUID      NOT NULL REFERENCES users (id),
    emoji              VARCHAR(20),
    comment            TEXT,
    comment_translated TEXT,
    created_at         TIMESTAMP NOT NULL
);

CREATE TABLE chat_messages (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id           BIGINT    NOT NULL REFERENCES matches (id),
    sender_id          UUID      NOT NULL REFERENCES users (id),
    content            TEXT      NOT NULL,
    content_translated TEXT,
    created_at         TIMESTAMP NOT NULL,
    read_at            TIMESTAMP
);
CREATE INDEX idx_chat_match_id ON chat_messages (match_id, id);

CREATE TABLE albums (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id   BIGINT    NOT NULL UNIQUE REFERENCES matches (id),
    title      VARCHAR(100),
    cover_url  VARCHAR(500),
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE reviews (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id    BIGINT    NOT NULL REFERENCES matches (id),
    reviewer_id UUID      NOT NULL REFERENCES users (id),
    reviewee_id UUID      NOT NULL REFERENCES users (id),
    rating      INT       NOT NULL,
    content     TEXT,
    created_at  TIMESTAMP NOT NULL,
    CONSTRAINT uk_review_match_reviewer UNIQUE (match_id, reviewer_id)
);

CREATE TABLE notifications (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    UUID         NOT NULL REFERENCES users (id),
    type       VARCHAR(20)  NOT NULL,
    ref_id     BIGINT,
    message    VARCHAR(255) NOT NULL,
    is_read    BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP    NOT NULL
);
CREATE INDEX idx_noti_user_id ON notifications (user_id, id);

CREATE TABLE reports (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id    UUID        NOT NULL REFERENCES users (id),
    target_user_id UUID        NOT NULL REFERENCES users (id),
    match_id       BIGINT      NOT NULL REFERENCES matches (id),
    target_type    VARCHAR(20) NOT NULL,
    target_id      BIGINT      NOT NULL,
    reason         VARCHAR(30) NOT NULL,
    detail         TEXT,
    status         VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    created_at     TIMESTAMP   NOT NULL,
    CONSTRAINT uk_report_once UNIQUE (reporter_id, match_id, target_user_id)
);

CREATE TABLE blocks (
    blocker_id UUID      NOT NULL REFERENCES users (id),
    blocked_id UUID      NOT NULL REFERENCES users (id),
    match_id   BIGINT REFERENCES matches (id),
    created_at TIMESTAMP NOT NULL,
    PRIMARY KEY (blocker_id, blocked_id)
);

